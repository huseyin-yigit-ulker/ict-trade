"""RSA-OAEP key envelope for per-user Binance API keys.

The browser encrypts key+secret with the VM's PUBLIC key (WebCrypto RSA-OAEP-SHA256,
SPKI import — see src/utils/keycrypt.js), so ict_trade.user_api_keys only ever stores
ciphertext. This module is the VM-side counterpart: decrypt with the PRIVATE key
(PEM on disk, path from .env EXEC_PRIV_KEY_PATH, generated by scripts/gen_exec_keypair.py).

encrypt_b64() exists for the seed path (sync/users/seed_owner.py imports the operator's
.env keys as if a browser had submitted them) and for tests — it derives the public key
from the private PEM so there is exactly one key source.
"""
from __future__ import annotations

import base64
import os
import sys
from pathlib import Path

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding

_HERE = Path(__file__).resolve()
sys.path.insert(0, str(_HERE.parents[1]))            # sync/ -> trade_sync_common
import trade_sync_common as tsc                       # noqa: E402

# Must match src/utils/keycrypt.js: RSA-OAEP with SHA-256 for both hash and MGF1, no label.
_OAEP = padding.OAEP(mgf=padding.MGF1(algorithm=hashes.SHA256()),
                     algorithm=hashes.SHA256(), label=None)


def _priv_path() -> Path:
    env = {**tsc._read_env(), **os.environ}
    p = env.get("EXEC_PRIV_KEY_PATH", "").strip()
    if not p:
        raise SystemExit("EXEC_PRIV_KEY_PATH not set in .env — run scripts/gen_exec_keypair.py first.")
    return Path(p).expanduser()


def load_private_key(path: str | Path | None = None):
    pem = Path(path).expanduser() if path else _priv_path()
    return serialization.load_pem_private_key(pem.read_bytes(), password=None)


def decrypt_b64(ciphertext_b64: str, priv=None) -> str:
    priv = priv or load_private_key()
    return priv.decrypt(base64.b64decode(ciphertext_b64), _OAEP).decode("utf-8")


def encrypt_b64(plaintext: str, pub=None) -> str:
    pub = pub or load_private_key().public_key()
    return base64.b64encode(pub.encrypt(plaintext.encode("utf-8"), _OAEP)).decode("ascii")


def public_spki_b64(priv=None) -> str:
    """The base64(SPKI DER) the frontend needs as VITE_EXEC_PUBKEY_B64."""
    pub = (priv or load_private_key()).public_key()
    der = pub.public_bytes(encoding=serialization.Encoding.DER,
                           format=serialization.PublicFormat.SubjectPublicKeyInfo)
    return base64.b64encode(der).decode("ascii")
