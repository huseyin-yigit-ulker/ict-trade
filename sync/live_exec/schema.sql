-- ict_trade.live_positions / ict_trade.live_orders — the d30so8c Binance live-execution layer.
--
-- IDEMPOTENT (safe to run against the existing DB and to reproduce on a fresh project), same
-- style as supabase/trading_signals_schema.sql. The reconciler (sync/live_exec/executor.py)
-- owns these tables: live_positions = one row per managed position (the DB-side INTENT), and
-- live_orders = the raw forensic log of every place/cancel/fill (fee reconciliation).
--
-- The closed result is ALSO upserted into ict_trade.trading_signals (version='d30so8c') via
-- tsc.upsert_rows, so the live track-record lands on the same dashboard curve as the backtest.

create schema if not exists ict_trade;

-- ------------------------------------------------------------------ live_positions
create table if not exists ict_trade.live_positions (
  id               bigint generated by default as identity primary key,
  symbol           varchar      not null,
  signal_time      timestamptz  not null,                  -- bar OPEN (the dch30_4h signal time)
  version          varchar      not null default 'd30so8c',
  direction        text         not null,                  -- 'LONG' | 'SHORT'
  side             text         not null,                  -- 'BUY' | 'SELL' (entry side)
  entry_mode       text         not null default 'B',      -- 'A' | 'B'

  -- signal reference levels (breakout close + structural stop/cap)
  signal_entry     numeric      not null,                  -- entry_close
  signal_sl        numeric      not null,                  -- structural full stop (entry_close ∓ risk0)
  signal_cap       numeric      not null,                  -- structural +runner_cap_r price (row tp_price)
  risk0            numeric      not null,                  -- |entry_close - sl|

  -- effective (fill-anchored) levels
  eff_entry        numeric,                                -- avgFillPrice once filled (intent: confirm level)
  eff_sl           numeric,                                -- = signal_sl (full close)
  eff_tp1          numeric,                                -- avgFill + 1*risk_eff
  eff_be           numeric,                                -- runner breakeven (= avgFill)
  eff_cap          numeric,                                -- = signal_cap (structural)

  -- sizing
  qty              numeric,                                -- total contract qty
  tp1_qty          numeric,                                -- floored close_frac leg
  runner_qty       numeric,                                -- real residual after TP1 (from positionRisk)
  leverage         integer,

  -- lifecycle
  state            text         not null default 'PENDING_ENTRY',
  entry_deadline   timestamptz,                            -- fire + expiry_min (cancel if unfilled)
  time_stop_at     timestamptz,                            -- entry_fill + horizon_days (mark-to-market)
  entry_fill_time  timestamptz,
  entry_fill_px    numeric,
  tp1_fill_time    timestamptz,
  tp1_fill_px      numeric,
  exit_time        timestamptz,
  exit_px          numeric,
  exit_reason      text,                                   -- sl|tp1_be|cap|breakeven|time_stop|entry_expired
  realized_r       numeric,
  realized_usd     numeric,

  -- deterministic clientOrderIds + resolved exchange orderIds (per leg)
  entry_coid       text,  entry_order_id   bigint,
  sl_coid          text,  sl_order_id      bigint,
  tp1_coid         text,  tp1_order_id     bigint,
  be_coid          text,  be_order_id      bigint,
  cap_coid         text,  cap_order_id     bigint,

  context          jsonb        default '{}'::jsonb,
  created_at       timestamptz  default current_timestamp,
  updated_at       timestamptz  default current_timestamp
);

-- "act once": a duplicate dch30_4h signal (same bar/direction) is a no-op insert.
create unique index if not exists uq_live_positions_key
  on ict_trade.live_positions (symbol, signal_time, direction, version);

-- One managed position per symbol at a time (DB-level guard for the one-position overlay).
create unique index if not exists uq_live_positions_open_symbol
  on ict_trade.live_positions (symbol)
  where state in ('PENDING_ENTRY','ENTRY_WORKING','OPEN_FULL','RUNNER','CLOSING');

create index if not exists live_positions_state_idx on ict_trade.live_positions (state);

-- ------------------------------------------------------------------ live_orders
create table if not exists ict_trade.live_orders (
  id               bigint generated by default as identity primary key,
  position_id      bigint       references ict_trade.live_positions(id),
  symbol           varchar      not null,
  leg              text,                                   -- entry|sl|tp1|be|cap
  action           text         not null,                  -- place|cancel|fill|error
  client_order_id  text,
  order_id         bigint,
  payload          jsonb,                                  -- raw request/response
  created_at       timestamptz  default current_timestamp
);

create index if not exists live_orders_position_idx on ict_trade.live_orders (position_id);
create index if not exists live_orders_symbol_idx on ict_trade.live_orders (symbol);

-- ------------------------------------------------------------------ live exchange snapshot
-- The REAL Binance state, refreshed by the executor each */2 run (account + positionRisk), so the
-- dashboard can show live mark / unrealized PnL / wallet without the browser ever signing a request.
create table if not exists ict_trade.live_account_snapshot (
  symbol          varchar      primary key,
  network         text,                                   -- 'testnet' | 'mainnet'
  position_amt    numeric,                                -- signed contracts (0 = flat)
  entry_price     numeric,
  mark_price      numeric,
  unrealized_pnl  numeric,
  leverage        integer,
  funding_fee     numeric,                                -- FUNDING_FEE income since entry (<0 = we paid)
  updated_at      timestamptz  default current_timestamp
);
-- additive: backfill the funding column onto an already-created snapshot table
alter table ict_trade.live_account_snapshot add column if not exists funding_fee numeric;

create table if not exists ict_trade.live_account (
  network            text       primary key,              -- one row per network
  wallet_balance     numeric,
  available_balance  numeric,
  total_unrealized   numeric,
  can_trade          boolean,
  updated_at         timestamptz default current_timestamp
);

-- PostgREST read access for the dashboard (mirrors how ict_trade.signals is read by the frontend).
grant usage on schema ict_trade to anon, authenticated;
grant select on ict_trade.live_positions        to anon, authenticated;
grant select on ict_trade.live_account_snapshot  to anon, authenticated;
grant select on ict_trade.live_account           to anon, authenticated;
