-- ict_trade.talos_positions / ict_trade.talos_orders — the TALOS (gold XAUUSDT Keltner-trend)
-- Binance live-execution layer. SEPARATE from ict_trade.live_positions (OPUS/Donchian) on purpose:
--   * real-money isolation — TALOS's safety_sweep/killswitch iterate only XAUUSDT and only TALOS rows,
--     so the two executors can never flatten each other's positions;
--   * TALOS has no TP1/BE/runner legs (it rides a single ratcheting chandelier stop), so it needs its
--     own lean lifecycle columns rather than NULLing the Donchian scale-out columns;
--   * additive `create table if not exists` never touches the running OPUS table.
--
-- The reconciler (sync/talos_exec/executor.py) is the ONLY writer of these tables. The closed result
-- is ALSO upserted into ict_trade.trading_signals (version='talosx') so a live TALOS trade lands on the
-- dashboard next to (but distinct from) its paper twin 'talos' — which the nightly backfill DELETEs.
--
-- IDEMPOTENT: safe to run against the existing DB and to reproduce on a fresh project.

create schema if not exists ict_trade;

-- ------------------------------------------------------------------ talos_positions
create table if not exists ict_trade.talos_positions (
  id               bigint generated by default as identity primary key,
  symbol           varchar      not null,                  -- always XAUUSDT
  signal_time      timestamptz  not null,                  -- the mode='talos' signal bar OPEN time
  version          varchar      not null default 'talosx',
  direction        text         not null,                  -- 'LONG' | 'SHORT'
  side             text         not null,                  -- 'BUY' | 'SELL' (entry side)

  -- signal reference levels (VWAP-trend pullback signal close + 1.5*ATR initial stop)
  signal_entry     numeric      not null,                  -- signal-bar close (maker limit reference)
  signal_sl        numeric      not null,                  -- entry ∓ 1.5*ATR (the initial 1R stop)
  risk0            numeric      not null,                  -- |signal_entry - signal_sl| = 1R distance

  -- effective (fill-anchored) + live trailing state
  eff_entry        numeric,                                -- real avg fill price
  cur_sl           numeric,                                -- current chandelier stop (mutates each ratchet)
  best             numeric,                                -- running best price since fill (chandelier anchor)
  locked_r         numeric,                                -- (cur_sl - entry)/risk in R (can be < 0 early)
  trail_gen        integer      not null default 0,        -- bumps each resting-stop cancel/replace (mainnet)

  -- sizing
  qty              numeric,
  leverage         integer,

  -- lifecycle: PENDING_ENTRY -> ENTRY_WORKING -> OPEN -> CLOSED / CANCELLED
  state            text         not null default 'PENDING_ENTRY',
  entry_deadline   timestamptz,                            -- cancel an unfilled maker entry after this
  time_stop_at     timestamptz,                            -- entry_fill + 8h (MAX_HOLD_MIN) hard cap
  entry_fill_time  timestamptz,
  entry_fill_px    numeric,
  exit_time        timestamptz,
  exit_px          numeric,
  exit_reason      text,                                   -- trail/stop | time | session | slipped | unfilled | closed_externally | killswitch
  realized_r       numeric,
  realized_usd     numeric,

  -- deterministic clientOrderIds + resolved exchange orderIds (per leg)
  entry_coid       text,  entry_order_id   bigint,
  sl_coid          text,  sl_order_id      bigint,

  context          jsonb        default '{}'::jsonb,       -- {kind:'trailing', init_sl, tp_ref, trail:[[t,px]…], placed_sl, pos, exit_px, pnl_r, strategy}
  -- multi-user scope (mirrors migrations 005a/005b, baked in from birth for TALOS)
  user_id          uuid,
  network          text,
  created_at       timestamptz  default current_timestamp,
  updated_at       timestamptz  default current_timestamp
);

-- "act once": a duplicate talos signal (same bar/direction) is a no-op insert (user-scoped).
create unique index if not exists uq_talos_positions_key
  on ict_trade.talos_positions (user_id, network, symbol, signal_time, direction, version)
  nulls not distinct;

-- One managed TALOS position per (user, network, symbol) at a time (single-position rule).
create unique index if not exists uq_talos_positions_open_symbol
  on ict_trade.talos_positions (user_id, network, symbol)
  nulls not distinct
  where state in ('PENDING_ENTRY','ENTRY_WORKING','OPEN');

create index if not exists talos_positions_user_idx on ict_trade.talos_positions (user_id, state);

create index if not exists talos_positions_state_idx on ict_trade.talos_positions (state);

-- ------------------------------------------------------------------ talos_orders (forensic log)
create table if not exists ict_trade.talos_orders (
  id               bigint generated by default as identity primary key,
  position_id      bigint       references ict_trade.talos_positions(id),
  symbol           varchar      not null,
  leg              text,                                   -- entry | sl | exit | reverse
  action           text         not null,                  -- place | cancel | fill | error
  client_order_id  text,
  order_id         bigint,
  payload          jsonb,
  user_id          uuid,
  created_at       timestamptz  default current_timestamp
);

create index if not exists talos_orders_position_idx on ict_trade.talos_orders (position_id);
create index if not exists talos_orders_symbol_idx on ict_trade.talos_orders (symbol);

-- ------------------------------------------------------------------ shared live exchange snapshot
-- Reused from the OPUS layer (strategy-agnostic; keyed by symbol/network). Recreated here with
-- IF NOT EXISTS so the TALOS schema is self-sufficient on a fresh project where live_exec/schema.sql
-- was never applied. TALOS writes the XAUUSDT row + the account row each run; OPUS writes its own
-- symbols — no key collision (OPUS never trades XAUUSDT).
create table if not exists ict_trade.live_account_snapshot (
  symbol          varchar      primary key,
  network         text,
  position_amt    numeric,
  entry_price     numeric,
  mark_price      numeric,
  unrealized_pnl  numeric,
  leverage        integer,
  funding_fee     numeric,                                -- FUNDING_FEE income since entry (<0 = we paid)
  updated_at      timestamptz  default current_timestamp
);
alter table ict_trade.live_account_snapshot add column if not exists funding_fee numeric;

create table if not exists ict_trade.live_account (
  network            text       primary key,
  wallet_balance     numeric,
  available_balance  numeric,
  total_unrealized   numeric,
  can_trade          boolean,
  updated_at         timestamptz default current_timestamp
);

-- PostgREST read access for the dashboard (mirrors ict_trade.live_positions grants).
grant usage on schema ict_trade to anon, authenticated;
grant select on ict_trade.talos_positions        to anon, authenticated;
grant select on ict_trade.live_account_snapshot   to anon, authenticated;
grant select on ict_trade.live_account            to anon, authenticated;
