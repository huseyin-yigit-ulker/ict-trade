-- ict_trade.trading_signals — backtest/track-record table read by the dashboard
-- (src/context/TradeContext.jsx loadBacktest) and the RPCs in backtest_analytics.sql.
--
-- This file is IDEMPOTENT and matches the live schema exactly, so it is safe to run
-- against the existing DB (no-op on columns) and reproduces the table on a fresh project.
-- The only thing it ADDS to the current live DB is the unique index needed for
-- idempotent upserts by the backfill/daily-sync jobs (sync/).

create schema if not exists ict_trade;

create table if not exists ict_trade.trading_signals (
  id               bigint generated by default as identity primary key,
  symbol           varchar       not null,
  trade_type       varchar       not null,                 -- 'BUY' | 'SELL'
  signal_time      timestamptz   not null,                 -- bar OPEN time
  signal_price     numeric,                                -- reference price at signal (= entry)
  entry_price      numeric,
  sl_price         numeric,
  tp_price         numeric,
  status           varchar       default 'pending',        -- closed_tp|closed_sl|cancelled|active
  real_entry_time  timestamptz,                            -- entry bar CLOSE time (null if never filled)
  exit_time        timestamptz,                            -- exit bar CLOSE time
  exit_price       numeric,
  pnl_r            numeric,                                 -- R-multiple (+ for tp, -1 for sl)
  created_at       timestamptz   default current_timestamp,
  version          varchar       default 'v1',             -- dashboard filters version='v1'
  direction        text,                                   -- 'LONG' | 'SHORT'
  strategy         text,
  quality          text,
  confluence_score integer
);

-- Idempotency key for upserts (backfill + daily sync). No duplicates exist on this
-- tuple in current data, so creating it is safe.
create unique index if not exists uq_trading_signals_key
  on ict_trade.trading_signals (symbol, signal_time, trade_type, version);

-- Single-column indexes (names match the original DB so this is a no-op there and
-- only materializes them on a fresh project).
create index if not exists trading_signals_signal_time_idx
  on ict_trade.trading_signals (signal_time);
create index if not exists trading_signals_symbol_idx
  on ict_trade.trading_signals (symbol);
create index if not exists trading_signals_version_idx
  on ict_trade.trading_signals (version);

